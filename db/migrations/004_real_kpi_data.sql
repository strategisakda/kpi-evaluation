insert into public.evaluation_data (district, kpi_id, status)
select d.district, k.kpi_id,
  case when k.requires_evidence then 'ยังไม่ส่ง' else 'รอตรวจ' end
from (values
  ('ควนขนุน'), ('เมืองพัทลุง'), ('ป่าบอน'), ('ศรีนครินทร์'), ('เขาชัยสน'),
