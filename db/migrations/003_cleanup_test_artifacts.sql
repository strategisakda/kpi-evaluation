-- ลบแถวทดสอบที่ district ไม่ตรงกับอำเภอจริงทั้ง 3 (คือแถวเพี้ยนที่สร้างระหว่างทดสอบ)
delete from public.evaluation_data
where district not in ('อำเภอ A', 'อำเภอ B', 'อำเภอ C');

delete from public.history
where district not in ('อำเภอ A', 'อำเภอ B', 'อำเภอ C');

-- แก้ note ที่เพี้ยนของแถว P3/อำเภอ A (district ถูกต้องอยู่แล้ว เพี้ยนแค่ note)
update public.evaluation_data
set note = 'หลักฐานทดสอบ P3'
where district = 'อำเภอ A' and kpi_id = 'P3';
